import type { Timestamps } from "./common";
import type { ChannelType } from "./fixtureTemplates";

/**
 * A group of Selectables (options) on a fixture group, e.g. "Colour" with Red / Blue / Amber.
 * The LD sets these up; users pick selectables per cue.
 *
 * Keep in sync with OptionSet in server/internal/models/v2/option_set.go.
 * Rules (resolver, write order, safe edits) are in docs/v2-implementation-notes.md.
 */
export type OptionSet = Timestamps & {
  id: string;
  fixtureGroupId: string;

  name: string;
  description: string;

  /** Order of appearance. */
  sortOrder: number;
  /** TODO(draw.io): application order; remove if the visualiser doesn't need it. */
  priority: number;

  selectionType: OptionSetSelectionType;
  type: OptionSetType;

  /** Selectable order is the array position. */
  selectables: Selectable[];
  /** Copied into a cue when it is created. */
  defaultSelectableIds: string[];

  /** Whether the set must have a pick, or can be left empty. */
  required: boolean;
};

/** No `id` = create, `id` = update. `fixtureGroupId` comes from the URL. */
export type UpsertOptionSet = Omit<Partial<OptionSet>, "fixtureGroupId" | "createdAt" | "updatedAt" | "deletedAt">;

export const OptionSetSelectionType = {
  SINGLE: "SINGLE",
  MULTI: "MULTI",
  BOOL: "BOOL",
} as const;
export type OptionSetSelectionType = (typeof OptionSetSelectionType)[keyof typeof OptionSetSelectionType];

/**
 * The Option Set Type determines what sort of
 * input method is shown to the user.
 *
 * For example: Intensity option set type is configured to show Slider
 *              Colour shows custom color select dropdown
 *              Position TBD
 */
export const OptionSetType = {
  INTENSITY: "Intensity",
  COLOUR: "Colour",
  POSITION: "Position",
  CUSTOM: "Custom",
  /** A plain dropdown of names. No effect on DMX. */
  VALUELESS: "Valueless",
} as const;
export type OptionSetType = (typeof OptionSetType)[keyof typeof OptionSetType];

// --- Selectables (JSON inside OptionSet.selectables) ---------------------------------

/**
 * SelectableTypes defines how values are applied to fixtures.
 * For example:
 *    AppSelectableIntensity & value 40%: App knows to set the intensity channel to 40% for all fixtures in the group.
 *   AppSelectableColour & value Red: App knows to set the red channel to 100% for all fixtures in the group.
 *     It also knows if there is CMY instead, to use those channels instead.
 *
 * In short, the difference between OptionSetType and SelectableType:
 *   OptionSetType: configure how the website presents the selection
 *   SelectableType: configure how the website applies the selection to the fixtures
 */
export const SelectableType = {
  INTENSITY: "AppSelectableIntensity",
  COLOUR: "AppSelectableColour",
  POSITION: "AppSelectablePosition",
  CUSTOM: "AppCustom",
  EFFECT_PATTERN: "AppSelectableEffectPattern",
  EFFECT_MOVEMENT: "AppSelectableEffectMovement",
  VALUELESS: "AppValueless",
} as const;
export type SelectableType = (typeof SelectableType)[keyof typeof SelectableType];

/** Fields every selectable has. */
export type SelectableBase = {
  /** Generated by our code, not by Postgres. Unique within the option set. */
  id: string;
  name: string;
  /** Which fixtures this applies to. "all" (the default) includes fixtures added to the group later. */
  fixtureIds: string[] | "all";
};

export type IntensitySelectable = SelectableBase & {
  type: typeof SelectableType.INTENSITY;
  /** 0–100 */
  percent: number;
};

export type ColourSelectable = SelectableBase & {
  type: typeof SelectableType.COLOUR;
  colour: Colour;
};

export type PositionSelectable = SelectableBase & {
  type: typeof SelectableType.POSITION;
  /** Per fixture. A fixture without an entry is skipped. */
  positions: { [fixtureId: string]: Position };
};

export type CustomSelectable = SelectableBase & {
  type: typeof SelectableType.CUSTOM;
  /** Found by ChannelType on each fixture. */
  common: CommonChannelValue[];
  /** One fixture's channels by id; overrides `common`. */
  individual: { [fixtureId: string]: IndividualChannelValue[] };
};

export type PatternSelectable = SelectableBase & {
  type: typeof SelectableType.EFFECT_PATTERN;
  /** The algorithm. */
  effect: PatternEffect;
  colours: Colour[];
  /** Default "normal". */
  blendMode: BlendMode;
  /** Default "rgb". */
  colourMode: ColourMode;
  /** fadeIn + hold. TODO(draw.io): unit (ms?). */
  stepDuration: number;
  /** Default 0. */
  fadeInDuration: number;
  /** Default 0. */
  fadeOutDuration: number;
};

export type MovementSelectable = SelectableBase & {
  type: typeof SelectableType.EFFECT_MOVEMENT;
  /** The algorithm. */
  effect: MovementEffect;
  /** TODO(notes): ints in the design; change to 0–1 floats or write down the range. */
  width: number;
  height: number;
  offsetX: number;
  offsetY: number;
  /** Default 20 s. TODO(draw.io): unit (ms?). */
  loopTime: number;
  /** Optional; a missing fixture uses the defaults. */
  fixtureOverrides?: { [fixtureId: string]: MovementFixtureOverride };
  spread: number;
};

/** A label only: the resolver ignores it, so it has no effect on DMX, preview or export. */
export type ValuelessSelectable = SelectableBase & {
  type: typeof SelectableType.VALUELESS;
};

/** One option inside an option set. `type` decides which fields it has. */
export type Selectable =
  | IntensitySelectable
  | ColourSelectable
  | PositionSelectable
  | CustomSelectable
  | PatternSelectable
  | MovementSelectable
  | ValuelessSelectable;

// --- Values used by selectables ---------------------------------------------------

/**
 * One colour for all fixtures. `hex` is the complete look (always full brightness; brightness comes from intensity).
 * `mix` is an optional exact recipe, used only by fixtures that have every channel it sets above 0.
 */
export type Colour = {
  name: string;
  /** #rrggbb */
  hex: string;
  mix?: ColourMix;
};

/** 0–255 per channel. */
export type ColourMix = {
  r?: number;
  g?: number;
  b?: number;
  white?: number;
  amber?: number;
  uv?: number;
  lime?: number;
  indigo?: number;
};

/** All 0–65535 (16-bit, as DMX), not degrees. */
export type Position = {
  pan: number;
  tilt: number;
  /** Missing = don't write, so another option set can control it. */
  zoom?: number;
  focus?: number;
};

export type CommonChannelValue = {
  /** Which channel type (e.g. red) this applies to on each fixture. */
  type: ChannelType;
  /** Whether this targets the fine channel. */
  fine: boolean;
  /** 0–255 */
  value: number;
};

export type IndividualChannelValue = {
  channelId: string;
  /** 0–255 */
  value: number;
};

export type MovementFixtureOverride = {
  /** Added on top of `spread`, like QLC+. */
  startOffset?: number;
  reverse?: boolean;
};

/** Pattern effect blend modes (QLC+ RGB Matrix): see "Selectables" in the implementation notes. */
export const BlendMode = {
  NORMAL: "normal",
  MASK: "mask",
  ADDITIVE: "additive",
  SUBTRACTIVE: "subtractive",
} as const;
export type BlendMode = (typeof BlendMode)[keyof typeof BlendMode];

// TODO(draw.io): ColourMode values are not defined yet; "rgb" is the design's default.
export const ColourMode = {
  RGB: "rgb",
} as const;
export type ColourMode = (typeof ColourMode)[keyof typeof ColourMode];

// TODO(draw.io): PatternEffect and MovementEffect values are not defined yet.
export type PatternEffect = string;
export type MovementEffect = string;
