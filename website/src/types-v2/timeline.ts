import type { Timestamps } from "./common";

/**
 * An item's main timeline: syncs its cues to audio. One per item; variants are AlternateTimelines (later).
 * Timeline mode itself is switched with `Item.timelineEnabled`.
 *
 * All times are WHOLE milliseconds (the server rejects fractions): round every value you compute.
 * Keep in sync with server/internal/models/v2/timeline.go.
 */
export type Timeline = Timestamps &
  TimelineFields & {
    id: string;
    itemId: string;
    alternateTimelines?: AlternateTimeline[];
  };

/** A variant of an item's main timeline. Its markers still point to the item's main cues. */
export type AlternateTimeline = Timestamps &
  TimelineFields & {
    id: string;
    timelineId: string;
  };

/** Shared by Timeline and AlternateTimeline. */
export type TimelineFields = {
  sections: TimelineSection[];
  audios: TimelineAudio[];
  /** Snapping of audio clips and sections. */
  snapEnabled: boolean;
};

export const TimelineSectionType = {
  /** Beats at a BPM. */
  BEAT: "beat",
  /** A plain length in ms. */
  TIME: "time",
} as const;
export type TimelineSectionType = (typeof TimelineSectionType)[keyof typeof TimelineSectionType];

type TimelineSectionBase = {
  /** Generated by the frontend. */
  id: string;
  /** e.g. "Verse 1" */
  name: string;
  /** ms from the timeline start. */
  sectionStartTime: number;
  /** The last cue in the section effectively has a "hold time" of infinite */
  linkToNext: boolean;
  markers: TimelineMarker[];
  /** Snapping of markers inside this section. */
  snapEnabled: boolean;
};

export type TimelineBeatSection = TimelineSectionBase & {
  type: typeof TimelineSectionType.BEAT;
  /**
   * The time signature only groups beats into bars (bar lines, labels). It doesn't affect the length, so changing it
   * never moves a marker: 12 beats are 3 bars of 4/4 or 4 bars of 3/4.
   */
  timeSigNum: number;
  timeSigDenom: number;
  /** Counts the denominator's note (6/8 at 120 = 120 eighth notes a minute). May be fractional. */
  bpm: number;
  /** Length in beats (the denominator's note), whole, ≥ 1. Need not be whole bars. */
  beats: number;
  /** how many snappable points are there per timeSigDenom. 4 = 16th notes. 1 = match the timeSigDenom
   * Special values:
   * 1: snap every beat.
   * 0: snap every bar.
   */
  snapFidelity: number; // e.g. time signature 4/4 and this is 2 or 4, then the snap division is 8th note or 16th note. Time sigature 4/4, and this is 3, then snap division is dotted 8th note. Time signature 6/8, and this is 2, then snap division is quarter note.
};

export type TimelineTimeSection = TimelineSectionBase & {
  type: typeof TimelineSectionType.TIME;
  totalTimeMs: number;
  /** Enum TBD in the design. */
  snapDivisionTime?: string;
};

export type TimelineSection = TimelineBeatSection | TimelineTimeSection;

export const TimelineMarkerType = {
  CUE: "cue",
} as const;
export type TimelineMarkerType = (typeof TimelineMarkerType)[keyof typeof TimelineMarkerType];

export type TimelineCueMarker = {
  /** Generated by the frontend. */
  id: string;
  /** ms from the section start, 0 ≤ time ≤ the section's length. */
  time: number;
  type: typeof TimelineMarkerType.CUE;
  /** Always a main cue of the item. */
  cueId: string;
  /** If set, play this alternate of `cueId` instead. */
  alternateCueId?: string;
};

export type TimelineMarker = TimelineCueMarker;

/**
 * One clip on the audio row: a non-destructive trim of an AudioFile. Plays the file from `offset` for `duration`,
 * placed at `startTime`. Clips don't overlap.
 */
export type TimelineAudio = {
  /** Generated by the frontend. */
  id: string;
  /** ms from the timeline start. */
  startTime: number;
  /** ms into the file where playback starts (trimmed start). Default 0. */
  offset: number;
  /** ms the clip plays. Defaults to the file's durationMs; offset + duration ≤ durationMs. */
  duration: number;
  audioFileId: string;
  metadata?: Record<string, unknown>;
};

/**
 * Saves the item's main timeline (created if the item has none). A field left out keeps its value;
 * `sections` and `audios` are each replaced as a whole. The item comes from the URL.
 */
export type UpsertTimeline = Partial<TimelineFields>;

/**
 * How long a section lasts, in whole ms. Must match SectionLengthMs in server/internal/models/v2/timeline_validate.go:
 * a beat is 60000 / bpm ms (the time signature plays no part), and the total is rounded.
 */
export const getSectionLengthMs = (section: TimelineSection): number =>
  section.type === TimelineSectionType.BEAT ? Math.round((section.beats * 60000) / section.bpm) : section.totalTimeMs;
