import type { Timestamps } from "./common";

/**
 * A CueSketch-specific (console-agnostic) fixture template.
 *
 * The `FixtureTemplates` table acts as a global library.
 * However, when events are created, the fixture template is copied into the event.
 *
 * so, events don't depend on the library after creation
 *
 */
export type FixtureTemplate = Timestamps & {
  id: string;
  name: string;
  manufacturer: string;
  model: string;
  type: FixtureType;

  channels: Channel[];
  /** Only one mode is supported for now. */
  modes: Mode[];
  properties: PhysicalProperties;

  /** Link to the 3D model. */
  modelUrl: string;

  /** Where the template was imported from. */
  importType: ConsoleType;
  /** The original imported file (e.g. the .qxf XML), kept for re-export. */
  rawSource: string;
};

// TODO(draw.io): FixtureType values are not defined yet ("par, bar, moving head etc").
export const FixtureType = {
  PAR: "par",
  BAR_BEAM: "bar_beam",
  BAR_PIXEL: "bar_pixel",
  MOVING_HEAD: "moving head",
  LED: "led",
  SCANNER: "scanner",
  CUSTOM: "custom",
} as const;
export type FixtureType = (typeof FixtureType)[keyof typeof FixtureType];

// TODO(draw.io): ConsoleType values are not defined yet.
export const ConsoleType = {
  QLCPLUS: "qlcplus",
  GRANDMA: "grandMA",
  GRANDMA2: "grandMA2",
  GRANDMA3: "grandMA3",
  CHAMSYS: "chamsys",
  EOS: "eos",
  CUSTOM: "custom",
} as const;
export type ConsoleType = (typeof ConsoleType)[keyof typeof ConsoleType];

/** One DMX channel. IDs are generated by our code, not by Postgres. */
export type Channel = {
  id: string;
  name: string;
  /** 0–255. Defaults to 0. */
  defaultValue: number;
  /** Undefined for a custom channel. */
  preset?: ChannelPreset;
  capabilities: ChannelCapability[];
  type: ChannelType;
  role: ChannelRole;
  /**
   * The channel runs the other way (e.g. QLC+ `BeamZoomBigSmall`, `ShutterStrobeFastSlow`).
   * From the implementation notes; not in the diagram yet.
   */
  reversed?: boolean;
};

/** Helps to set the channel's type. */
export type ChannelPreset = {
  type?: ChannelType;
};

/** One labelled DMX range on a channel, e.g. 1–255 "Strobe slow to fast". */
export type ChannelCapability = {
  /** 0–255 */
  from: number;
  /** 0–255, >= from */
  to: number;
  description: string;
};

export const ChannelRole = {
  COARSE: "COARSE",
  FINE: "FINE",
} as const;
export type ChannelRole = (typeof ChannelRole)[keyof typeof ChannelRole];

// TODO(draw.io): ChannelType values are not defined yet. These are the ones the
// resolver rules in the implementation notes rely on.
export const ChannelType = {
  // intensity
  INTENSITY: "intensity",
  /** Controls the whole fixture, whichever head the source file lists it in. */
  MASTER_DIMMER: "masterDimmer",
  /** Controls one head. */
  DIMMER: "dimmer",
  // colour mixing
  RED: "red",
  GREEN: "green",
  BLUE: "blue",
  WHITE: "white",
  AMBER: "amber",
  UV: "uv",
  LIME: "lime",
  INDIGO: "indigo",
  CYAN: "cyan",
  MAGENTA: "magenta",
  YELLOW: "yellow",
  // colour, other
  COLOUR_WHEEL: "colourWheel",
  // position
  PAN: "pan",
  TILT: "tilt",
  // beam
  SHUTTER: "shutter",
  ZOOM: "zoom",
  FOCUS: "focus",
  IRIS: "iris",
  GOBO: "gobo",
  PRISM: "prism",
  // anything else
  CUSTOM: "custom",
} as const;
export type ChannelType = (typeof ChannelType)[keyof typeof ChannelType];

export type Mode = {
  /** Generated by our code, not by Postgres. */
  id: string;
  /** QLC+ refers to modes by name; match by name only at import/export. */
  name: string;
  channelIds: string[];
  /** No heads = one head containing all channels (QLC+ behaviour). */
  heads: Head[];
};

export type Head = {
  name: string;
  /** Positions in the mode's `channelIds`. Safe because heads are rebuilt with the mode. */
  channelIndexes: number[];
};

export type PhysicalProperties = {
  columns: number;
  rows: number;
  maxPan: number;
  maxTilt: number;
  /** Equal to maxBeamAngle when the fixture can't zoom. */
  minBeamAngle: number;
  maxBeamAngle: number;
  /** CueSketch-only: how bright the fixture looks in the visualiser. */
  brightnessModifier: number;
};
