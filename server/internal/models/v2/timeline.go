package v2

import (
	"encoding/json"

	"gorm.io/datatypes"
)

// TimelineSectionType says which of TimelineSection's type-specific fields apply.
type TimelineSectionType string

const (
	// Beats at a BPM; uses TimeSigNum, TimeSigDenom, Bpm, Beats, SnapFidelity.
	TimelineSectionTypeBeat TimelineSectionType = "beat"
	// A plain length in ms; uses TotalTimeMs, SnapDivisionTime.
	TimelineSectionTypeTime TimelineSectionType = "time"
)

// TimelineMarkerType says which of TimelineMarker's type-specific fields apply.
type TimelineMarkerType string

const (
	// Uses CueId.
	TimelineMarkerTypeCue TimelineMarkerType = "cue"
)

// JSON structs stored inside Timeline. Ids are generated by the frontend.
// Keep these in sync with website/src/types-v2/timeline.ts.

// TimelineSection is one block on the section row. Only the fields for its
// Type are set; the others are omitted.
type TimelineSection struct {
	Id   string              `json:"id"`
	Name string              `json:"name"` // e.g. "Verse 1"
	Type TimelineSectionType `json:"type"`

	SectionStartTime int `json:"sectionStartTime"` // ms from the timeline start
	// false: the last cue marker in this section holds forever (until the next
	// section is started manually).
	LinkToNext bool `json:"linkToNext"`

	Markers     []TimelineMarker `json:"markers"`
	SnapEnabled bool             `json:"snapEnabled"` // snapping of markers inside this section

	// type "beat"
	// The time signature only groups beats into bars (bar lines, labels); it
	// doesn't affect the length, so changing it never moves a marker.
	TimeSigNum   *int `json:"timeSigNum,omitempty"`
	TimeSigDenom *int `json:"timeSigDenom,omitempty"`
	// Counts the denominator's note (6/8 at 120 = 120 eighth notes a minute).
	Bpm *float64 `json:"bpm,omitempty"`
	// Length in beats (the denominator's note). Need not be whole bars.
	Beats *int `json:"beats,omitempty"`
	// Snap points per beat: 0 = every bar, 1 = every beat, 4 = 16ths in 4/4.
	SnapFidelity *int `json:"snapFidelity,omitempty"`

	// type "time"
	TotalTimeMs      *int    `json:"totalTimeMs,omitempty"`
	SnapDivisionTime *string `json:"snapDivisionTime,omitempty"` // enum TBD in the design
}

// TimelineMarker sits inside a section. Only the fields for its Type are set.
type TimelineMarker struct {
	Id   string             `json:"id"`
	Time int                `json:"time"` // ms from the section start
	Type TimelineMarkerType `json:"type"`

	// type "cue"
	CueId *string `json:"cueId,omitempty"` // always a main cue of the item
	// If set, play this alternate of CueId instead. Deleting the alternate
	// clears this (the marker falls back to CueId).
	AlternateCueId *string `json:"alternateCueId,omitempty"`
}

// TimelineAudio is one clip on the audio row: a non-destructive trim of an
// AudioFile. It plays the file from Offset for Duration, placed at StartTime.
type TimelineAudio struct {
	Id        string `json:"id"`
	StartTime int    `json:"startTime"` // ms from the timeline start
	// ms into the file where playback starts (trimmed start). Default 0.
	Offset int `json:"offset"`
	// ms the clip plays. Defaults to the file's durationMs; offset + duration ≤ durationMs.
	Duration    int             `json:"duration"`
	AudioFileId string          `json:"audioFileId"`
	Metadata    json.RawMessage `json:"metadata,omitempty"`
}

// DB model

// UpsertTimelineReq: the item comes from the URL (one main timeline per item),
// so there is no id. Creates the timeline if the item has none. A field left
// out keeps its current value; sections and audios are each replaced as a whole.
type UpsertTimelineReq struct {
	Sections    *[]TimelineSection `json:"sections,omitempty"`
	Audios      *[]TimelineAudio   `json:"audios,omitempty"`
	SnapEnabled *bool              `json:"snapEnabled,omitempty"`
}

// UpsertTimelineReqBody is the body of POST /api/v2/events/{eventId}/items/{itemId}/timeline.
type UpsertTimelineReqBody struct {
	Timeline UpsertTimelineReq `json:"timeline"`
}

// TimelineFields are shared by Timeline and AlternateTimeline.
type TimelineFields struct {
	Sections datatypes.JSONSlice[TimelineSection] `json:"sections" gorm:"type:jsonb;not null;default:'[]'"`
	Audios   datatypes.JSONSlice[TimelineAudio]   `json:"audios" gorm:"type:jsonb;not null;default:'[]'"`

	// Snapping of audio clips and sections. Defaults to true, set in code (the
	// frontend sends it on create; the handler falls back to true). No DB default:
	// GORM leaves a false bool with a default out of the INSERT, so false would become true.
	SnapEnabled bool `json:"snapEnabled" gorm:"not null"`
}

// Normalize turns missing lists into empty ones, so the JSON always has
// [] instead of null (sections, audios, and each section's markers).
func (f *TimelineFields) Normalize() {
	if f.Sections == nil {
		f.Sections = datatypes.JSONSlice[TimelineSection]{}
	}
	if f.Audios == nil {
		f.Audios = datatypes.JSONSlice[TimelineAudio]{}
	}
	for i := range f.Sections {
		if f.Sections[i].Markers == nil {
			f.Sections[i].Markers = []TimelineMarker{}
		}
	}
}

// RemoveCueMarkers deletes every marker that points to cueId. Reports whether
// anything was removed.
func (f *TimelineFields) RemoveCueMarkers(cueId string) bool {
	removed := false
	for i := range f.Sections {
		kept := f.Sections[i].Markers[:0]
		for _, m := range f.Sections[i].Markers {
			if m.CueId != nil && *m.CueId == cueId {
				removed = true
				continue
			}
			kept = append(kept, m)
		}
		f.Sections[i].Markers = kept
	}
	return removed
}

// Timeline is an item's main timeline (exactly one per item): syncs its cues
// to audio. Variants are AlternateTimelines, like Cue and AlternateCue.
// An item has timeline mode on when it has a Timeline.
type Timeline struct {
	Base

	ItemId string `json:"itemId" gorm:"type:uuid;not null;uniqueIndex"`

	TimelineFields

	AlternateTimelines []AlternateTimeline `json:"alternateTimelines,omitempty" gorm:"foreignKey:TimelineId"`
}

func (Timeline) TableName() string { return "v2.timelines" }

// AlternateTimeline is a variant of an item's main Timeline. Its markers
// still point to the item's main cues.
type AlternateTimeline struct {
	Base

	TimelineId string `json:"timelineId" gorm:"type:uuid;not null;index"`

	TimelineFields
}

func (AlternateTimeline) TableName() string { return "v2.alternate_timelines" }
